/**
 * Regenerates src/core/math/trigTable.ts. Run with `npm run gen:trig`.
 * The output is committed, so the simulation never computes trig at runtime.
 */
import { writeFileSync } from "node:fs";
import { computeSinTable, QUARTER_STEPS } from "./trig/sinTable.ts";

const table = computeSinTable();
const out = new URL("../src/core/math/trigTable.ts", import.meta.url);

const source = `// GENERATED by tools/gen-trig.ts. Do not edit by hand.
/** Quarter-wave sine table: sin(i / ${QUARTER_STEPS} × π/2) in Q16.16, i = 0..${QUARTER_STEPS}. */
export const SIN_QUARTER_TABLE: readonly number[] = [${table.join(", ")}];
`;

writeFileSync(out, source);
console.log(`Wrote ${table.length} entries to ${out.pathname}`);
