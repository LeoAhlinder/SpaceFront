/**
 * Packs every sprite (tools/atlas/sprites.ts) into one SVG sheet:
 *   public/atlas/atlas.svg              the atlas the game loads (one image)
 *   src/client/render/atlasFrames.ts    frame rectangles, typed by sprite name
 *   assets/sprites/<name>.svg           each sprite on its own, for review
 *
 * Run with `npm run atlas`. The output is deterministic, so it is committed.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { SPRITES } from "./sprites";

const ATLAS_WIDTH = 1024;
/** Empty pixels around each frame, so linear filtering never bleeds a neighbor in. */
const PAD = 2;

interface Placed {
  readonly name: string;
  readonly x: number;
  readonly y: number;
  readonly size: number;
  readonly radius?: number;
}

/** Shelf packing: frames left to right, a new row when one doesn't fit. */
function pack(): { placed: Placed[]; height: number } {
  const placed: Placed[] = [];
  let x = 0;
  let y = 0;
  let rowH = 0;
  for (const s of SPRITES) {
    const w = s.size + 2 * PAD;
    if (x + w > ATLAS_WIDTH) {
      x = 0;
      y += rowH;
      rowH = 0;
    }
    placed.push({
      name: s.name,
      x: x + PAD,
      y: y + PAD,
      size: s.size,
      ...(s.radius !== undefined && { radius: s.radius }),
    });
    x += w;
    rowH = Math.max(rowH, w);
  }
  return { placed, height: y + rowH };
}

function main(): void {
  const root = new URL("../../", import.meta.url);
  const { placed, height } = pack();
  const frames = placed
    .map((p) => {
      const s = SPRITES.find((d) => d.name === p.name)!;
      return `<svg x="${p.x}" y="${p.y}" width="${p.size}" height="${p.size}" viewBox="0 0 ${p.size} ${p.size}">${s.svg}</svg>`;
    })
    .join("\n");
  const atlas = `<svg xmlns="http://www.w3.org/2000/svg" width="${ATLAS_WIDTH}" height="${height}" viewBox="0 0 ${ATLAS_WIDTH} ${height}">\n<!-- SpaceFront sprite atlas. Generated by tools/atlas (npm run atlas); original art. -->\n${frames}\n</svg>\n`;
  mkdirSync(new URL("public/atlas/", root), { recursive: true });
  writeFileSync(new URL("public/atlas/atlas.svg", root), atlas);

  mkdirSync(new URL("assets/sprites/", root), { recursive: true });
  for (const s of SPRITES) {
    writeFileSync(
      new URL(`assets/sprites/${s.name}.svg`, root),
      `<svg xmlns="http://www.w3.org/2000/svg" width="${s.size}" height="${s.size}" viewBox="0 0 ${s.size} ${s.size}">${s.svg}</svg>\n`,
    );
  }

  const lines = placed.map(
    (p) =>
      `  ${p.name}: { x: ${p.x}, y: ${p.y}, size: ${p.size}${p.radius !== undefined ? `, radius: ${p.radius}` : ""} },`,
  );
  const ts = `// Generated by tools/atlas/pack.ts (npm run atlas). Do not edit by hand.

/** One square frame of the sprite atlas, in atlas pixels. */
export interface AtlasFrame {
  readonly x: number;
  readonly y: number;
  readonly size: number;
  /** Planet icons: the disc's radius in frame pixels. */
  readonly radius?: number;
}

export const ATLAS_WIDTH = ${ATLAS_WIDTH};
export const ATLAS_HEIGHT = ${height};

export const ATLAS_FRAMES = {
${lines.join("\n")}
} as const satisfies Record<string, AtlasFrame>;

export type SpriteName = keyof typeof ATLAS_FRAMES;
`;
  writeFileSync(new URL("src/client/render/atlasFrames.ts", root), ts);
  console.log(`Atlas: ${placed.length} frames, ${ATLAS_WIDTH}×${height}`);
}

main();
